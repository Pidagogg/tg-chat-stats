export const TEXTS = { en, ru };
export type Texts = typeof en;

export function detectLang(): Lang {
  const tg = (window as unknown as { Telegram?: { WebApp?: { initDataUnsafe?: { user?: { language_code?: string } } } } }).Telegram;
  const code = tg?.WebApp?.initDataUnsafe?.user?.language_code || navigator.language || "en";
  return /^(ru|uk|be|kk)/i.test(code) ? "ru" : "en";
}

export function formatDuration(seconds: number | null, lang: Lang) {
  if (seconds === null) return "—";
  const u = lang === "ru" ? { s: "с", m: "мин", h: "ч" } : { s: "s", m: "min", h: "h" };
  if (seconds < 60) return `${seconds} ${u.s}`;
  if (seconds < 3600) return `${Math.round(seconds / 60)} ${u.m}`;
  return `${Math.round((seconds / 3600) * 10) / 10} ${u.h}`;
}
